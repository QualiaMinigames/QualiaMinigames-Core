    /// Returns whether an independent scan clears a board.
    ///
    /// The scan is deliberately naive and does not share the generator's queue: it looks at
    /// every remaining block after every take, which is a second implementation of the take
    /// rule and the only kind of solver that can catch the generator agreeing with itself.
    fn clears_with_scanning(shape: Shape, blocks: &[Block]) -> bool {
        let mut occupancy = rebuild_occupancy(shape, blocks);
        let mut removed = vec![false; blocks.len()];
        let mut remaining = blocks.len();
        while remaining > 0 {
            let Some(index) = (0..blocks.len()).find(|index| {
                !removed[*index] && !empty_directions(&blocks[*index], &occupancy, shape).is_empty()
            }) else {
                return false;
            };
            removed[index] = true;
            for cell in blocks[index].cells() {
                occupancy[cell as usize] = NO_BLOCK;
            }
            remaining -= 1;
        }
        true
    }

    /// Returns whether a directed graph over `nodes` nodes has a cycle.
    fn has_cycle(nodes: usize, edges: &[(u32, u32)]) -> bool {
        let mut outgoing: Vec<Vec<u32>> = vec![Vec::new(); nodes];
        for (from, to) in edges {
            outgoing[*from as usize].push(*to);
        }
        let mut state = vec![0_u8; nodes];
        /// Walks one node and reports whether it reaches a node already on the path.
        fn visit(node: usize, outgoing: &[Vec<u32>], state: &mut [u8]) -> bool {
            if state[node] == 1 {
                return true;
            }
            if state[node] == 2 {
                return false;
            }
            state[node] = 1;
            for next in &outgoing[node] {
                if visit(*next as usize, outgoing, state) {
                    return true;
                }
            }
            state[node] = 2;
            false
        }
        (0..nodes).any(|node| visit(node, &outgoing, &mut state))
    }

    /// Reads a little-endian `u32` from a snapshot.
    fn read_u32(bytes: &[u8], offset: usize) -> u32 {
        u32::from_le_bytes(
            bytes[offset..offset + 4]
                .try_into()
                .expect("the field is four bytes"),
        )
    }

    /// Writes a little-endian `u32` into a snapshot.
    fn write_u32(bytes: &mut [u8], offset: usize, value: u32) {
        bytes[offset..offset + 4].copy_from_slice(&value.to_le_bytes());
    }
