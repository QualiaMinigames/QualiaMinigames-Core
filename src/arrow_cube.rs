//! Arrow Cube: pulling blocks with arrows out of a solid rectangular box.
//!
//! # The board
//!
//! A board is `width` cells along x (east), `depth` cells along y (north) and `height`
//! cells along z (up), each side between [`MIN_SIZE`] and [`MAX_SIZE`]. The cell index is
//! `x + width × (y + depth × z)`. Every cell belongs to exactly one block, so the box is
//! solid: there are no holes to move through except the spaces left by blocks already
//! taken out.
//!
//! # Blocks and arrows
//!
//! A block is either one cell or two cells long. A two-cell block lies along one axis and
//! its arrow points along that axis, out of one of its two one-cell end faces; a one-cell
//! block may point in any of the six directions. The four faces perpendicular to the arrow
//! carry its decal: an arrow pointing north is drawn on the east, west, up and down faces
//! and not on the north or south ends. A two-cell block's long faces are one by two, so the
//! decal spans both cells rather than being repeated on each of them.
//!
//! # Taking a block out
//!
//! A block leaves along its arrow. Starting at the face the arrow points out of, every
//! cell in that direction up to the edge of the box has to be empty; the first block on
//! the way is the blocker. A two-cell block moves along its long axis, so the swept column
//! is one cell wide and both of its cells are cleared together. A take that meets a
//! blocker counts as a mistake and leaves the board as it was; a take that does not is
//! final, because the game has no undo.
//!
//! # Generation
//!
//! The board is generated by building an answer rather than by searching for one. The box
//! is filled with blocks at random, then blocks are peeled off from the full box, each one
//! given a direction that is clear at the moment it is peeled. Playing the same order takes
//! the board apart, so a generated board is always solvable. The arrows are random within
//! the legal directions, which deliberately allows a board where an arrow is hidden behind
//! another block: the generator promises that a way out exists, not that every arrow is
//! visible.
//!
//! # Snapshot
//!
//! A snapshot holds the seed, the three sides, the generation version, the number of blocks,
//! the mistakes and a bitmap of the blocks already taken out. The board itself is rebuilt
//! from the seed, so the file stays small: a 30 by 30 by 30 board needs 3,375 bytes of
//! bitmap. [`GENERATION_VERSION`] rises when the tiling or the arrow choice changes; the
//! global format version does not, because the other games' saves keep working.

use std::cmp::Reverse;
use std::collections::BinaryHeap;

use crate::random::Random;
use crate::snapshot::{FORMAT_VERSION, Reader, SnapshotError, Writer};

/// The smallest board, in cells on a side.
pub const MIN_SIZE: u32 = 5;

/// The largest board, in cells on a side.
pub const MAX_SIZE: u32 = 30;

/// The chance that a cell starts a two-cell block, in thousandths.
pub const DOMINO_PER_MILLE: u32 = 350;

/// The version of the tiling and the arrow choice.
///
/// It is separate from [`FORMAT_VERSION`] so that changing how a board is generated does
/// not invalidate the saves of the other five games. A snapshot names the version it was
/// written under and is refused when this build generates differently.
pub const GENERATION_VERSION: u8 = 1;

/// How many linear keys the fallback candidate may choose from.
///
/// The fallback picks the remaining cell with the smallest key under one of these positive
/// linear forms. More than one form keeps the fallback from always peeling the same corner
/// of the box while every form still guarantees the clear ray the fallback relies on.
pub const KEY_VARIANTS: usize = 48;

/// The number of directions a block can point in.
pub const DIRECTION_COUNT: usize = 6;

/// The number of bits one byte of the removed bitmap holds.
const BITS_PER_BYTE: usize = 8;

/// The value the occupancy grid holds for a cell no block occupies.
const NO_BLOCK: u32 = u32::MAX;

/// The derived-stream number of the tiling and peeling draws.
const TILING_STREAM: u8 = 0;

/// The derived-stream number of the key variant.
const KEY_STREAM: u8 = 1;

/// One of the three axes a block can lie along.
#[derive(Clone, Copy, Debug, Eq, Hash, PartialEq)]
pub enum Axis {
    /// The x axis, towards the east.
    X,
    /// The y axis, towards the north.
    Y,
    /// The z axis, upwards.
    Z,
}

impl Axis {
    /// Returns the step from one cell to the next along the axis.
    ///
    /// The step is a coordinate delta rather than a flat index because its size depends on
    /// the board: adding one along y is one row, which is `width` cells in the index.
    #[must_use]
    pub fn step(&self) -> (i32, i32, i32) {
        match self {
            Self::X => (1, 0, 0),
            Self::Y => (0, 1, 0),
            Self::Z => (0, 0, 1),
        }
    }
}

/// One of the six directions a block's arrow can point.
#[derive(Clone, Copy, Debug, Eq, Hash, PartialEq)]
pub enum Direction {
    /// Towards larger x.
    East,
    /// Towards smaller x.
    West,
    /// Towards larger y.
    North,
    /// Towards smaller y.
    South,
    /// Towards larger z.
    Up,
    /// Towards smaller z.
    Down,
}

impl Direction {
    /// The six directions, in a fixed order.
    const ALL: [Self; DIRECTION_COUNT] = [
        Self::East,
        Self::West,
        Self::North,
        Self::South,
        Self::Up,
        Self::Down,
    ];

    /// Returns the axis the direction runs along.
    #[must_use]
    pub fn axis(&self) -> Axis {
        match self {
            Self::East | Self::West => Axis::X,
            Self::North | Self::South => Axis::Y,
            Self::Up | Self::Down => Axis::Z,
        }
    }

    /// Returns the direction that faces the other way.
    #[must_use]
    pub fn opposite(&self) -> Self {
        match self {
            Self::East => Self::West,
            Self::West => Self::East,
            Self::North => Self::South,
            Self::South => Self::North,
            Self::Up => Self::Down,
            Self::Down => Self::Up,
        }
    }

    /// Returns the step from one cell to the next as a coordinate delta.
    #[must_use]
    pub fn step(&self) -> (i32, i32, i32) {
        match self {
            Self::East => (1, 0, 0),
            Self::West => (-1, 0, 0),
            Self::North => (0, 1, 0),
            Self::South => (0, -1, 0),
            Self::Up => (0, 0, 1),
            Self::Down => (0, 0, -1),
        }
    }
}

/// Returns the direction along an axis towards larger coordinates.
fn positive_direction(axis: Axis) -> Direction {
    match axis {
        Axis::X => Direction::East,
        Axis::Y => Direction::North,
        Axis::Z => Direction::Up,
    }
}

/// Returns the direction along an axis towards smaller coordinates.
fn negative_direction(axis: Axis) -> Direction {
    positive_direction(axis).opposite()
}

/// Returns a stable number for a direction, used when a bad value has to be reported.
fn direction_number(direction: Direction) -> u32 {
    match direction {
        Direction::East => 0,
        Direction::West => 1,
        Direction::North => 2,
        Direction::South => 3,
        Direction::Up => 4,
        Direction::Down => 5,
    }
}

/// Returns the width, depth and height coefficients of one linear key.
///
/// Every coefficient is positive, which is what makes the fallback work: the cell with the
/// smallest key has nothing but empty cells on the three negative rays, so the block that
/// owns it can leave along the negative side of an axis. The forty-eight triples are
/// distinct and stay small enough for a key to fit a `u32` on the largest board.
fn key_coefficients(variant: usize) -> [u32; 3] {
    let variant = variant % KEY_VARIANTS;
    [
        1 + (variant % 4) as u32,
        1 + ((variant / 4) % 4) as u32,
        1 + (variant / 16) as u32,
    ]
}

/// Derives one of the two random streams a board is generated from.
///
/// This is 64-bit FNV-1a over the base seed, the generation version and the stream number,
/// all little-endian. The version is part of the input rather than part of the hash's
/// parameters, so a future generation can raise it and leave the boards of today
/// reproducible under the version they recorded.
fn derive_seed(base: u64, version: u8, stream: u8) -> u64 {
    /// The FNV-1a offset basis for 64-bit hashing.
    const OFFSET_BASIS: u64 = 0xcbf2_9ce4_8422_2325;
    /// The FNV-1a prime for 64-bit hashing.
    const PRIME: u64 = 0x0000_0100_0000_01b3;
    let mut hash = OFFSET_BASIS;
    for byte in base.to_le_bytes().into_iter().chain([version, stream]) {
        hash ^= u64::from(byte);
        hash = hash.wrapping_mul(PRIME);
    }
    hash
}

/// The dimensions of a board and the arithmetic that maps cells to coordinates.
///
/// A block carries the shape it was cut from, because a flat origin index on its own cannot
/// be turned back into an x, y and z without knowing the box it came from.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
struct Shape {
    /// The number of cells along x.
    width: u32,
    /// The number of cells along y.
    depth: u32,
    /// The number of cells along z.
    height: u32,
}

impl Shape {
    /// Returns how many cells the box holds.
    fn cell_count(&self) -> u32 {
        self.width * self.depth * self.height
    }

    /// Returns the flat index of a cell.
    fn index(&self, x: u32, y: u32, z: u32) -> u32 {
        x + self.width * (y + self.depth * z)
    }

    /// Returns the coordinates of a flat index.
    fn coords(&self, cell: u32) -> (u32, u32, u32) {
        let plane = self.width * self.depth;
        (
            cell % self.width,
            (cell / self.width) % self.depth,
            cell / plane,
        )
    }

    /// Returns the flat distance between the two cells of a block on an axis.
    fn step_index(&self, axis: Axis) -> u32 {
        match axis {
            Axis::X => 1,
            Axis::Y => self.width,
            Axis::Z => self.width * self.depth,
        }
    }

    /// Returns the index one step from a cell, or `None` when the step leaves the box.
    fn neighbor(&self, cell: u32, direction: Direction) -> Option<u32> {
        let (x, y, z) = self.coords(cell);
        let (dx, dy, dz) = direction.step();
        let x = i64::from(x) + i64::from(dx);
        let y = i64::from(y) + i64::from(dy);
        let z = i64::from(z) + i64::from(dz);
        if x < 0
            || x >= i64::from(self.width)
            || y < 0
            || y >= i64::from(self.depth)
            || z < 0
            || z >= i64::from(self.height)
        {
            return None;
        }
        Some(self.index(x as u32, y as u32, z as u32))
    }

    /// Walks from a cell towards the edge of the box.
    ///
    /// Returns the first occupied cell and how many empty cells were crossed before it. A
    /// blocker right at the start is reported with a gap of zero, which is the distance a
    /// front end has to move a block to make it touch its blocker.
    fn cast(&self, occupancy: &[u32], start: u32, direction: Direction) -> (Option<u32>, u32) {
        let mut gap = 0;
        let mut current = start;
        loop {
            let occupant = occupancy[current as usize];
            if occupant != NO_BLOCK {
                return (Some(occupant), gap);
            }
            let Some(next) = self.neighbor(current, direction) else {
                return (None, gap);
            };
            gap += 1;
            current = next;
        }
    }
}

/// One block and the arrow painted on it.
///
/// A block of one cell has no long axis; it is stored with [`Axis::X`], and its direction
/// alone decides which faces carry the decal. A block of two cells always points along its
/// long axis, so its direction's axis equals its own.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct Block {
    /// The cell at the low end of the long axis.
    origin: u32,
    /// The shape of the board the block was cut from.
    shape: Shape,
    /// The axis the block is long along.
    axis: Axis,
    /// How many cells the block covers, one or two.
    length: u8,
    /// The direction its arrow points.
    direction: Direction,
    /// Whether it has been taken out of the box.
    removed: bool,
}

impl Block {
    /// Builds a block of one cell.
    fn single(shape: Shape, cell: u32) -> Self {
        Self {
            origin: cell,
            shape,
            axis: Axis::X,
            length: 1,
            direction: Direction::East,
            removed: false,
        }
    }

    /// Builds a block of two cells whose low cell is `origin`.
    fn domino(shape: Shape, origin: u32, axis: Axis) -> Self {
        Self {
            origin,
            shape,
            axis,
            length: 2,
            direction: positive_direction(axis),
            removed: false,
        }
    }

    /// Returns the x coordinate of the low cell.
    #[must_use]
    pub fn x(&self) -> u32 {
        self.shape.coords(self.origin).0
    }

    /// Returns the y coordinate of the low cell.
    #[must_use]
    pub fn y(&self) -> u32 {
        self.shape.coords(self.origin).1
    }

    /// Returns the z coordinate of the low cell.
    #[must_use]
    pub fn z(&self) -> u32 {
        self.shape.coords(self.origin).2
    }

    /// Returns the flat index of the low cell.
    #[must_use]
    pub fn origin(&self) -> u32 {
        self.origin
    }

    /// Returns the axis the block is long along.
    #[must_use]
    pub fn axis(&self) -> Axis {
        self.axis
    }

    /// Returns how many cells the block covers, one or two.
    #[must_use]
    pub fn length(&self) -> u8 {
        self.length
    }

    /// Returns the direction its arrow points.
    #[must_use]
    pub fn direction(&self) -> Direction {
        self.direction
    }

    /// Returns whether it has been taken out.
    #[must_use]
    pub fn removed(&self) -> bool {
        self.removed
    }

    /// Returns the cells the block covers, low cell first.
    pub fn cells(&self) -> impl Iterator<Item = u32> + '_ {
        let step = self.shape.step_index(self.axis);
        (0..u32::from(self.length)).map(move |offset| self.origin + offset * step)
    }

    /// Returns the second cell of a two-cell block.
    fn second_cell(&self) -> u32 {
        self.origin + self.shape.step_index(self.axis)
    }

    /// Returns the cell whose face the arrow leaves through.
    ///
    /// For a one-cell block either face is the same cell. For a two-cell block moving along
    /// its long axis, the front is the far cell in the arrow's direction, so the column it
    /// sweeps is one cell wide.
    fn front(&self, direction: Direction) -> u32 {
        if self.length == 2 && direction == positive_direction(self.axis) {
            self.second_cell()
        } else {
            self.origin
        }
    }
}

/// What one tap on a block did.
///
/// The four fields mirror the facts a screen needs: whether the block left, which block
/// stopped it and how far away that one was, and whether the board is finished. A tap the
/// rules ignore reports nothing and leaves `solved` where it was.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct TakeResult {
    /// Whether the block left the board.
    removed: bool,
    /// The block that stopped it, when one did.
    blocker: Option<u32>,
    /// How many empty cells lie between the moving block and the blocker.
    gap: u32,
    /// Whether the board is finished after this take.
    solved: bool,
}

impl TakeResult {
    /// Returns whether the block left the board.
    #[must_use]
    pub fn removed(&self) -> bool {
        self.removed
    }

    /// Returns the block that stopped it, when one did.
    #[must_use]
    pub fn blocker(&self) -> Option<u32> {
        self.blocker
    }

    /// Returns how many empty cells lie between the moving block and the blocker.
    #[must_use]
    pub fn gap(&self) -> u32 {
        self.gap
    }

    /// Returns whether the board is finished after this take.
    #[must_use]
    pub fn solved(&self) -> bool {
        self.solved
    }
}

/// A filled box and a player's progress through it.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct Game {
    /// The number of cells along x.
    width: u32,
    /// The number of cells along y.
    depth: u32,
    /// The number of cells along z.
    height: u32,
    /// The seed the board was generated from.
    seed: u64,
    /// Every block, in the fixed order the generator gave them.
    blocks: Vec<Block>,
    /// The block index of each cell, or [`NO_BLOCK`] where a block has left.
    occupancy: Vec<u32>,
    /// How many takes have met a blocker.
    mistakes: u32,
    /// How many blocks are still in the box.
    remaining: u32,
}

impl Game {
    /// Generates a board of this shape from a seed.
    ///
    /// Generation is part of the constructor rather than deferred to a first click: the
    /// board is a solid box whose every block exists from the start, so there is nothing
    /// left to lay down later.
    ///
    /// # Errors
    ///
    /// Returns [`SnapshotError::Parameter`] when a side is outside [`MIN_SIZE`] to
    /// [`MAX_SIZE`]; generation itself never fails.
    pub fn random(
        width: u32,
        depth: u32,
        height: u32,
        base_seed: u64,
    ) -> Result<Self, SnapshotError> {
        let shape = check(width, depth, height)?;
        let (blocks, _removal_order) = generate(shape, base_seed);
        Self::assemble(shape, base_seed, blocks, 0)
    }

    /// Returns the number of cells along x.
    #[must_use]
    pub fn width(&self) -> u32 {
        self.width
    }

    /// Returns the number of cells along y.
    #[must_use]
    pub fn depth(&self) -> u32 {
        self.depth
    }

    /// Returns the number of cells along z.
    #[must_use]
    pub fn height(&self) -> u32 {
        self.height
    }

    /// Returns the seed the board was generated from.
    #[must_use]
    pub fn seed(&self) -> u64 {
        self.seed
    }

    /// Returns how many cells the box holds.
    #[must_use]
    pub fn cell_count(&self) -> u32 {
        self.shape().cell_count()
    }

    /// Returns how many blocks the board was generated with.
    #[must_use]
    pub fn block_count(&self) -> u32 {
        self.blocks.len() as u32
    }

    /// Returns how many blocks are still in the box.
    #[must_use]
    pub fn remaining_count(&self) -> u32 {
        self.remaining
    }

    /// Returns how many takes have met a blocker.
    #[must_use]
    pub fn mistakes(&self) -> u32 {
        self.mistakes
    }

    /// Returns whether every block has left.
    #[must_use]
    pub fn is_solved(&self) -> bool {
        self.remaining == 0
    }

    /// Returns every block, taken ones included.
    ///
    /// The index of a block never changes, so a screen reads the list once and tracks the
    /// taken blocks locally instead of crossing the boundary again for each take.
    #[must_use]
    pub fn blocks(&self) -> &[Block] {
        &self.blocks
    }

    /// Returns the block that currently stops a block, if one does.
    ///
    /// This answers the same question as [`Self::take`] without counting a mistake, which is
    /// what a screen uses to decide whether a tap will move anything.
    #[must_use]
    pub fn blocker(&self, index: u32) -> Option<u32> {
        let block = self.blocks.get(index as usize)?;
        if block.removed || self.is_solved() {
            return None;
        }
        let start = self
            .shape()
            .neighbor(block.front(block.direction), block.direction)?;
        self.shape().cast(&self.occupancy, start, block.direction).0
    }

    /// Takes a block out along its arrow.
    ///
    /// A block that is out of range, already taken, or asked for after the board is solved
    /// changes nothing. A block that meets another one counts a mistake and leaves the board
    /// as it was; the returned blocker and gap let the screen show where the moving block
    /// stopped.
    pub fn take(&mut self, index: u32) -> TakeResult {
        let solved = self.is_solved();
        let Some(block) = self.blocks.get(index as usize).copied() else {
            return TakeResult {
                removed: false,
                blocker: None,
                gap: 0,
                solved,
            };
        };
        if block.removed || solved {
            return TakeResult {
                removed: false,
                blocker: None,
                gap: 0,
                solved,
            };
        }
        let shape = self.shape();
        let (blocker, gap) = match shape.neighbor(block.front(block.direction), block.direction) {
            Some(start) => shape.cast(&self.occupancy, start, block.direction),
            None => (None, 0),
        };
        if let Some(other) = blocker {
            self.mistakes += 1;
            return TakeResult {
                removed: false,
                blocker: Some(other),
                gap,
                solved: false,
            };
        }
        for cell in block.cells() {
            self.occupancy[cell as usize] = NO_BLOCK;
        }
        self.blocks[index as usize].removed = true;
        self.remaining -= 1;
        TakeResult {
            removed: true,
            blocker: None,
            gap: 0,
            solved: self.remaining == 0,
        }
    }

    /// Returns the shape of the board.
    fn shape(&self) -> Shape {
        Shape {
            width: self.width,
            depth: self.depth,
            height: self.height,
        }
    }

    /// Builds a game from a complete block table, checking that the table fits the box.
    ///
    /// Every block is put back in place, so this is the constructor of a fresh board rather
    /// than of a position in progress: a restored position starts from a fresh board and
    /// applies its bitmap afterwards.
    fn assemble(
        shape: Shape,
        seed: u64,
        blocks: Vec<Block>,
        mistakes: u32,
    ) -> Result<Self, SnapshotError> {
        let cells = shape.cell_count();
        let mut occupancy = vec![NO_BLOCK; cells as usize];
        let mut checked = Vec::with_capacity(blocks.len());
        for mut block in blocks {
            if block.length != 1 && block.length != 2 {
                return Err(SnapshotError::Parameter {
                    field: "block length",
                    value: u32::from(block.length),
                });
            }
            if block.length == 2 && block.axis != block.direction.axis() {
                return Err(SnapshotError::Parameter {
                    field: "block direction",
                    value: direction_number(block.direction),
                });
            }
            if block.origin >= cells {
                return Err(SnapshotError::Parameter {
                    field: "block origin",
                    value: block.origin,
                });
            }
            block.shape = shape;
            block.removed = false;
            if block.length == 2 {
                let (x, y, z) = shape.coords(block.origin);
                let (position, limit) = match block.axis {
                    Axis::X => (x, shape.width),
                    Axis::Y => (y, shape.depth),
                    Axis::Z => (z, shape.height),
                };
                if position + 1 >= limit {
                    return Err(SnapshotError::Parameter {
                        field: "block cells",
                        value: block.origin,
                    });
                }
            }
            for cell in block.cells() {
                if cell >= cells {
                    return Err(SnapshotError::Parameter {
                        field: "block cells",
                        value: cell,
                    });
                }
                if occupancy[cell as usize] != NO_BLOCK {
                    return Err(SnapshotError::Parameter {
                        field: "block cells",
                        value: cell,
                    });
                }
                occupancy[cell as usize] = checked.len() as u32;
            }
            checked.push(block);
        }
        let remaining = checked.len() as u32;
        Ok(Self {
            width: shape.width,
            depth: shape.depth,
            height: shape.height,
            seed,
            blocks: checked,
            occupancy,
            mistakes,
            remaining,
        })
    }

    /// Writes the game, so it can be saved and read back.
    #[must_use]
    pub fn to_snapshot(&self) -> Vec<u8> {
        let mut writer = Writer::new(FORMAT_VERSION);
        writer.u64(self.seed);
        writer.u32(self.width);
        writer.u32(self.depth);
        writer.u32(self.height);
        writer.u8(GENERATION_VERSION);
        writer.u32(self.block_count());
        writer.u32(self.mistakes);
        writer.block(&removed_bitmap(&self.blocks));
        writer.finish()
    }

    /// Reads a snapshot and rebuilds the game it holds.
    ///
    /// The block table is regenerated from the seed rather than stored, so the snapshot has
    /// to name the generation version it was written under: a save whose board this build
    /// would lay out differently is refused rather than restored with its taken blocks on
    /// the wrong pieces.
    ///
    /// # Errors
    ///
    /// Returns [`SnapshotError`] when the bytes are truncated, name another format or
    /// generation version, or hold parameters, a block count or a bitmap that do not
    /// describe the board the seed regenerates.
    pub fn from_snapshot(bytes: &[u8]) -> Result<Self, SnapshotError> {
        let mut reader = Reader::new(bytes)?;
        let seed = reader.u64()?;
        let width = reader.u32()?;
        let depth = reader.u32()?;
        let height = reader.u32()?;
        check(width, depth, height)?;
        let generation = reader.u8()?;
        if generation != GENERATION_VERSION {
            return Err(SnapshotError::Parameter {
                field: "generation version",
                value: u32::from(generation),
            });
        }
        let block_count = reader.u32()?;
        let mistakes = reader.u32()?;
        let bitmap = reader.block()?;

        let mut game = Self::random(width, depth, height, seed)?;
        if game.block_count() != block_count {
            return Err(SnapshotError::Parameter {
                field: "block count",
                value: block_count,
            });
        }
        let expected = bitmap_bytes(block_count as usize);
        if bitmap.len() != expected {
            return Err(SnapshotError::Parameter {
                field: "removed bitmap length",
                value: u32::try_from(bitmap.len()).unwrap_or(u32::MAX),
            });
        }
        reader.finish()?;
        let leftover = block_count as usize % BITS_PER_BYTE;
        if leftover != 0 {
            let mask = 0xff_u8 << leftover;
            let last = bitmap[expected - 1];
            if last & mask != 0 {
                return Err(SnapshotError::Parameter {
                    field: "removed bitmap",
                    value: u32::from(last & mask),
                });
            }
        }
        for index in 0..block_count {
            if bitmap[index as usize / BITS_PER_BYTE] & (1 << (index % BITS_PER_BYTE as u32)) == 0 {
                continue;
            }
            let block = game.blocks[index as usize];
            for cell in block.cells() {
                game.occupancy[cell as usize] = NO_BLOCK;
            }
            game.blocks[index as usize].removed = true;
            game.remaining -= 1;
        }
        game.mistakes = mistakes;
        Ok(game)
    }
}

/// Checks the three sides and returns the shape they describe.
fn check(width: u32, depth: u32, height: u32) -> Result<Shape, SnapshotError> {
    for (field, value) in [("width", width), ("depth", depth), ("height", height)] {
        if !(MIN_SIZE..=MAX_SIZE).contains(&value) {
            return Err(SnapshotError::Parameter { field, value });
        }
    }
    Ok(Shape {
        width,
        depth,
        height,
    })
}

/// Fills the box at random with single cells and two-cell blocks.
///
/// The cells are visited in a shuffled order and each unclaimed one starts a block. A
/// two-cell block is tried with a fixed probability; when it is tried, the six directions
/// are shuffled so the long axis is not biased towards the first one. A cell that cannot
/// start a two-cell block becomes a one-cell block, which is why the fill never fails.
fn tile(shape: Shape, random: &mut Random) -> (Vec<Block>, Vec<u32>) {
    let cells = shape.cell_count();
    let mut order: Vec<u32> = (0..cells).collect();
    random.shuffle(&mut order);
    let mut blocks: Vec<Block> = Vec::new();
    let mut occupancy = vec![NO_BLOCK; cells as usize];
    for cell in order {
        if occupancy[cell as usize] != NO_BLOCK {
            continue;
        }
        let mut placed = false;
        if random.below(1000) < DOMINO_PER_MILLE {
            let mut directions = Direction::ALL;
            random.shuffle(&mut directions);
            for direction in directions {
                let Some(other) = shape.neighbor(cell, direction) else {
                    continue;
                };
                if occupancy[other as usize] != NO_BLOCK {
                    continue;
                }
                let origin = cell.min(other);
                let index = blocks.len() as u32;
                blocks.push(Block::domino(shape, origin, direction.axis()));
                occupancy[cell as usize] = index;
                occupancy[other as usize] = index;
                placed = true;
                break;
            }
        }
        if !placed {
            let index = blocks.len() as u32;
            blocks.push(Block::single(shape, cell));
            occupancy[cell as usize] = index;
        }
    }
    (blocks, occupancy)
}

/// Makes sure a tiled box holds at least one block of each length.
///
/// The fill almost always produces both, but "almost always" is not a promise: a board made
/// only of single cells, or only of two-cell blocks, is still legal, and a game whose two
/// block kinds never appeared would be a different game. The fix happens before any block is
/// peeled, so the arrows chosen afterwards are chosen on the corrected board.
fn ensure_both_shapes(
    shape: Shape,
    blocks: &mut Vec<Block>,
    occupancy: &mut Vec<u32>,
    random: &mut Random,
) {
    if !blocks.iter().any(|block| block.length == 2) {
        merge_singletons(shape, blocks, occupancy, random);
    }
    if !blocks.iter().any(|block| block.length == 1) {
        split_domino(shape, blocks, occupancy, random);
    }
}

/// Joins two adjacent one-cell blocks into one two-cell block.
fn merge_singletons(
    shape: Shape,
    blocks: &mut Vec<Block>,
    occupancy: &mut Vec<u32>,
    random: &mut Random,
) {
    let mut pairs: Vec<(u32, u32, Axis)> = Vec::new();
    for (index, block) in blocks.iter().enumerate() {
        if block.length != 1 {
            continue;
        }
        for direction in [Direction::East, Direction::North, Direction::Up] {
            let Some(other_cell) = shape.neighbor(block.origin, direction) else {
                continue;
            };
            let other = occupancy[other_cell as usize];
            if other == NO_BLOCK || other == index as u32 {
                continue;
            }
            if blocks[other as usize].length == 1 {
                pairs.push((index as u32, other, direction.axis()));
            }
        }
    }
    debug_assert!(
        !pairs.is_empty(),
        "a box of one-cell blocks always holds an adjacent pair"
    );
    if pairs.is_empty() {
        return;
    }
    let chosen = random.below(u32::try_from(pairs.len()).expect("a vector fits a u32")) as usize;
    let (first, second, axis) = pairs[chosen];
    let origin = blocks[first as usize]
        .origin
        .min(blocks[second as usize].origin);
    let mut rebuilt: Vec<Block> = blocks
        .iter()
        .enumerate()
        .filter(|(index, _)| *index as u32 != first && *index as u32 != second)
        .map(|(_, block)| *block)
        .collect();
    rebuilt.push(Block::domino(shape, origin, axis));
    *blocks = rebuilt;
    *occupancy = rebuild_occupancy(shape, blocks);
}

/// Splits one two-cell block into two one-cell blocks.
fn split_domino(
    shape: Shape,
    blocks: &mut Vec<Block>,
    occupancy: &mut Vec<u32>,
    random: &mut Random,
) {
    let dominoes: Vec<u32> = blocks
        .iter()
        .enumerate()
        .filter(|(_, block)| block.length == 2)
        .map(|(index, _)| index as u32)
        .collect();
    debug_assert!(
        !dominoes.is_empty(),
        "a box of two-cell blocks holds one to split"
    );
    if dominoes.is_empty() {
        return;
    }
    let chosen = dominoes
        [random.below(u32::try_from(dominoes.len()).expect("a vector fits a u32")) as usize]
        as usize;
    let block = blocks[chosen];
    let mut rebuilt: Vec<Block> = blocks
        .iter()
        .enumerate()
        .filter(|(index, _)| *index != chosen)
        .map(|(_, block)| *block)
        .collect();
    rebuilt.push(Block::single(shape, block.origin));
    rebuilt.push(Block::single(shape, block.second_cell()));
    *blocks = rebuilt;
    *occupancy = rebuild_occupancy(shape, blocks);
}

/// Builds the occupancy grid from a complete block table.
fn rebuild_occupancy(shape: Shape, blocks: &[Block]) -> Vec<u32> {
    let mut occupancy = vec![NO_BLOCK; shape.cell_count() as usize];
    for (index, block) in blocks.iter().enumerate() {
        for cell in block.cells() {
            debug_assert_eq!(
                occupancy[cell as usize], NO_BLOCK,
                "two blocks cover cell {cell}"
            );
            occupancy[cell as usize] = index as u32;
        }
    }
    occupancy
}

/// Fills a box and peels it apart, returning the blocks and the order they were peeled in.
fn generate(shape: Shape, base_seed: u64) -> (Vec<Block>, Vec<u32>) {
    let mut random = Random::new(derive_seed(base_seed, GENERATION_VERSION, TILING_STREAM));
    let (mut blocks, mut occupancy) = tile(shape, &mut random);
    ensure_both_shapes(shape, &mut blocks, &mut occupancy, &mut random);
    let variant = Random::new(derive_seed(base_seed, GENERATION_VERSION, KEY_STREAM))
        .below(u32::try_from(KEY_VARIANTS).expect("the variant count fits a u32"))
        as usize;
    let coefficients = key_coefficients(variant);
    let order = peel(
        shape,
        &mut blocks,
        &mut occupancy,
        coefficients,
        &mut random,
    );
    (blocks, order)
}

/// Peels a full box apart, choosing a legal arrow for every block on the way.
///
/// The queue holds the blocks known to have at least one clear direction. Taking a block out
/// can only clear cells, so a block in the queue never loses that property. When the queue
/// runs dry the box is locally locked; the fallback picks the remaining cell with the
/// smallest key instead, whose block is guaranteed to have a clear negative ray. That keeps
/// the walk from stopping without giving up the property that matters: every chosen arrow
/// is legal at the moment its block leaves, so the recorded order is a solution.
fn peel(
    shape: Shape,
    blocks: &mut [Block],
    occupancy: &mut [u32],
    coefficients: [u32; 3],
    random: &mut Random,
) -> Vec<u32> {
    let count = blocks.len();
    let mut removed = vec![false; count];
    let mut queued = vec![false; count];
    let mut queue: Vec<u32> = Vec::new();
    for (index, block) in blocks.iter().enumerate() {
        if !empty_directions(block, occupancy, shape).is_empty() {
            queue.push(index as u32);
            queued[index] = true;
        }
    }
    let mut keys: BinaryHeap<Reverse<(u32, u32)>> = (0..shape.cell_count())
        .map(|cell| Reverse((linear_key(shape, cell, coefficients), cell)))
        .collect();
    let mut remaining = count;
    let mut order = Vec::with_capacity(count);
    while remaining > 0 {
        if queue.is_empty() {
            let cell = smallest_remaining_cell(&mut keys, occupancy);
            let index = occupancy[cell as usize];
            if !removed[index as usize] && !queued[index as usize] {
                queue.push(index);
                queued[index as usize] = true;
            }
        }
        let position =
            random.below(u32::try_from(queue.len()).expect("a queue fits a u32")) as usize;
        let index = queue.swap_remove(position);
        queued[index as usize] = false;
        if removed[index as usize] {
            continue;
        }
        let block = blocks[index as usize];
        let directions = empty_directions(&block, occupancy, shape);
        let direction = directions
            .choose(random)
            .expect("a block in the candidate queue keeps a clear direction");
        blocks[index as usize].direction = direction;
        blocks[index as usize].removed = true;
        removed[index as usize] = true;
        for cell in block.cells() {
            occupancy[cell as usize] = NO_BLOCK;
        }
        remaining -= 1;
        order.push(index);
        enqueue_neighbors(
            shape,
            blocks,
            occupancy,
            &mut queue,
            &mut queued,
            &removed,
            block,
        );
    }
    debug_assert!(
        verify_order(shape, blocks, &order),
        "the generation order does not clear the board"
    );
    order
}

/// Adds the blocks that a take may have set free to the candidate queue.
///
/// Only the first block along each of the six rays from a cleared cell can have changed:
/// everything behind it is still blocked by it. Rechecking that one per ray is what keeps
/// the walk linear in the number of blocks instead of rescanning the box after every take.
fn enqueue_neighbors(
    shape: Shape,
    blocks: &[Block],
    occupancy: &[u32],
    queue: &mut Vec<u32>,
    queued: &mut [bool],
    removed: &[bool],
    taken: Block,
) {
    for cell in taken.cells() {
        for direction in Direction::ALL {
            let Some(start) = shape.neighbor(cell, direction) else {
                continue;
            };
            let (blocker, _) = shape.cast(occupancy, start, direction);
            let Some(other) = blocker else {
                continue;
            };
            let slot = other as usize;
            if removed[slot] || queued[slot] {
                continue;
            }
            if empty_directions(&blocks[slot], occupancy, shape).is_empty() {
                continue;
            }
            queue.push(other);
            queued[slot] = true;
        }
    }
}

/// Returns the smallest remaining cell under the linear key.
///
/// The heap is ordered once and read lazily: a cell that has already been cleared is
/// dropped when it surfaces, so no key is recomputed and no removal needs a reorder.
fn smallest_remaining_cell(keys: &mut BinaryHeap<Reverse<(u32, u32)>>, occupancy: &[u32]) -> u32 {
    loop {
        let Reverse((_key, cell)) = keys
            .pop()
            .expect("the fallback runs only while a block is still in the box");
        if occupancy[cell as usize] != NO_BLOCK {
            return cell;
        }
    }
}

/// Returns the linear key of a cell.
fn linear_key(shape: Shape, cell: u32, coefficients: [u32; 3]) -> u32 {
    let (x, y, z) = shape.coords(cell);
    coefficients[0] * x + coefficients[1] * y + coefficients[2] * z
}

/// The set of directions a block can currently leave through.
#[derive(Clone, Copy, Debug)]
struct DirectionSet {
    /// The directions found, in the first `len` slots.
    directions: [Direction; DIRECTION_COUNT],
    /// How many slots are in use.
    len: usize,
}

impl DirectionSet {
    /// The set with no direction in it.
    const EMPTY: Self = Self {
        directions: [Direction::East; DIRECTION_COUNT],
        len: 0,
    };

    /// Adds one direction.
    fn push(&mut self, direction: Direction) {
        self.directions[self.len] = direction;
        self.len += 1;
    }

    /// Returns whether the set holds no direction.
    fn is_empty(&self) -> bool {
        self.len == 0
    }

    /// Returns whether the set holds a direction.
    fn contains(&self, direction: Direction) -> bool {
        self.directions[..self.len].contains(&direction)
    }

    /// Picks one direction at random, or `None` when there is none.
    fn choose(&self, random: &mut Random) -> Option<Direction> {
        if self.is_empty() {
            None
        } else {
            Some(self.directions[random.below(self.len as u32) as usize])
        }
    }
}

/// Returns the directions a block can leave through right now.
///
/// A two-cell block may only leave along its long axis, because moving it sideways would
/// sweep a one-by-two face two cells wide. A one-cell block has all six directions.
fn empty_directions(block: &Block, occupancy: &[u32], shape: Shape) -> DirectionSet {
    let mut set = DirectionSet::EMPTY;
    if block.length == 2 {
        for direction in [
            positive_direction(block.axis),
            negative_direction(block.axis),
        ] {
            if is_clear(block, direction, occupancy, shape) {
                set.push(direction);
            }
        }
    } else {
        for direction in Direction::ALL {
            if is_clear(block, direction, occupancy, shape) {
                set.push(direction);
            }
        }
    }
    set
}

/// Returns whether a block's ray in a direction is empty all the way to the edge.
fn is_clear(block: &Block, direction: Direction, occupancy: &[u32], shape: Shape) -> bool {
    let front = block.front(direction);
    match shape.neighbor(front, direction) {
        Some(start) => shape.cast(occupancy, start, direction).0.is_none(),
        None => true,
    }
}

/// Replays an order over a full box and reports whether every step is a legal take.
fn verify_order(shape: Shape, blocks: &[Block], order: &[u32]) -> bool {
    let mut occupancy = rebuild_occupancy(shape, blocks);
    let mut seen = vec![false; blocks.len()];
    for index in order {
        let slot = *index as usize;
        if slot >= blocks.len() || seen[slot] {
            return false;
        }
        seen[slot] = true;
        let block = blocks[slot];
        if !empty_directions(&block, &occupancy, shape).contains(block.direction) {
            return false;
        }
        for cell in block.cells() {
            occupancy[cell as usize] = NO_BLOCK;
        }
    }
    seen.iter().all(|hit| *hit) && occupancy.iter().all(|cell| *cell == NO_BLOCK)
}

/// Returns how many bytes a removed bitmap of this many blocks takes.
fn bitmap_bytes(blocks: usize) -> usize {
    blocks.div_ceil(BITS_PER_BYTE)
}

/// Packs the removed flags into bytes, eight blocks to a byte and the lowest block first.
fn removed_bitmap(blocks: &[Block]) -> Vec<u8> {
    let mut bytes = vec![0_u8; bitmap_bytes(blocks.len())];
    for (index, block) in blocks.iter().enumerate() {
        if block.removed {
            bytes[index / BITS_PER_BYTE] |= 1 << (index % BITS_PER_BYTE);
        }
    }
    bytes
}

