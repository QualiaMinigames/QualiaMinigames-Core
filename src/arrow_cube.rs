    #[test]
    fn every_blocking_edge_points_to_a_block_taken_earlier() {
        // The final board can hold a block in front of an earlier one that was already out
        // when the earlier one left, so an edge to an earlier take is legal. An edge to a
        // later take would mean the block was blocked at the moment it was peeled.
        let board = shape(5, 5, 5);
        let (blocks, order) = generate(board, 3);
        let mut position = vec![0_usize; blocks.len()];
        for (step, index) in order.iter().enumerate() {
            position[*index as usize] = step;
        }
        let occupancy = rebuild_occupancy(board, &blocks);
        let mut edges: Vec<(u32, u32)> = Vec::new();
        for (index, block) in blocks.iter().enumerate() {
            let Some(start) = board.neighbor(block.front(block.direction), block.direction) else {
                continue;
            };
            let (blocker, _) = board.cast(&occupancy, start, block.direction);
            let Some(other) = blocker else {
                continue;
            };
            assert!(
                position[other as usize] < position[index],
                "block {index} is blocked by block {other}, which leaves later"
            );
            edges.push((index as u32, other));
        }
        assert!(
            !has_cycle(blocks.len(), &edges),
            "the blocking graph has a cycle"
        );
    }

