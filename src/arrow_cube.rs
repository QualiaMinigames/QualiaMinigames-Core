    #[test]
    fn a_board_stays_solvable_after_random_takes() {
        // A player does not follow the generation order. Taking blocks at random has to leave a
        // board that can still be finished, which is the one property the interface relies on.
        let board = shape(5, 5, 5);
        let (blocks, _) = generate(board, 7);
        let mut game = Game::assemble(board, 7, blocks, 0).expect("the generated table is legal");
        let mut random = Random::new(99);
        for _ in 0..10 {
            let candidates: Vec<u32> = (0..game.block_count())
                .filter(|index| {
                    !game.blocks()[*index as usize].removed() && game.blocker(*index).is_none()
                })
                .collect();
            if candidates.is_empty() {
                break;
            }
            let chosen = candidates[random.below(candidates.len() as u32) as usize];
            assert!(game.take(chosen).removed());
        }
        while !game.is_solved() {
            let chosen = (0..game.block_count()).find(|index| {
                !game.blocks()[*index as usize].removed() && game.blocker(*index).is_none()
            });
            let chosen = chosen.expect("every position still offers a block");
            assert!(game.take(chosen).removed());
        }
        assert!(game.is_solved());
    }

